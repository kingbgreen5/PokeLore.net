import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const STATIC_REDIRECT_LIMIT = 2000;
export const DYNAMIC_REDIRECTS = [
  '/pokemon/:slug/ /pokemon/:slug 301',
  '/pokemon/:slug.html /pokemon/:slug 301'
];

export function generateRedirects(source) {
  // JSON.parse silently overwrites duplicate keys. Inspect the flat byId map
  // first so even repeated identical IDs fail rather than disappearing.
  const blocks = [...source.matchAll(/"byId"\s*:\s*\{([^{}]*)\}/g)];
  assert.equal(blocks.length, 1, 'Expected exactly one flat byId registry');
  const keys = [...blocks[0][1].matchAll(/("(?:\\.|[^"\\])*")\s*:/g)]
    .map(match => JSON.parse(match[1]));
  assert.equal(new Set(keys).size, keys.length, 'Duplicate numeric mappings in byId');
  const registry = JSON.parse(source);
  assert(registry.byId && registry.byName, 'Missing route registry mappings');
  assert.equal(keys.length, Object.keys(registry.byId).length, 'Invalid byId structure');
  assert(keys.length > 0, 'Empty route registry');
  assert(keys.length < STATIC_REDIRECT_LIMIT, 'Static redirects must remain below 2,000');
  const rules = keys.sort((a, b) => Number(a) - Number(b)).map(id => {
    const slug = registry.byId[id];
    assert(/^[1-9]\d*$/.test(id) && Number.isSafeInteger(Number(id)), `Invalid numeric ID: ${id}`);
    assert(typeof slug === 'string' && /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug) && !/^\d+$/.test(slug), `Invalid canonical slug for ${id}`);
    assert.equal(registry.byName[slug], Number(id), `Conflicting registry mapping: ${id} → ${slug}`);
    return `/pokemon/${id} /pokemon/${slug} 301`;
  });
  return {
    count: rules.length,
    text: [
      '# GENERATED by scripts/generate-redirects.mjs — do not edit manually.',
      '# Source: public/data/pokemonRoutes.json in the parent repository.',
      ...rules,
      '# Explicit permanent normalization; static rules must come first.',
      ...DYNAMIC_REDIRECTS,
      ''
    ].join('\n')
  };
}

export function registryRedirects() {
  return generateRedirects(readFileSync(new URL('../../public/data/pokemonRoutes.json', import.meta.url), 'utf8'));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = registryRedirects();
  const target = fileURLToPath(new URL('../public/_redirects', import.meta.url));
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, result.text);
  console.log(`Generated ${result.count} static numeric redirects and ${DYNAMIC_REDIRECTS.length} dynamic 301 rules.`);
}
