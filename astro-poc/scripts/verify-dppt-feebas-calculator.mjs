import assert from 'node:assert/strict';
import { existsSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { gzipSync } from 'node:zlib';
import { parseHTML } from 'linkedom';

const dist = join(process.cwd(), 'dist');
const file = join(dist, 'dppt-feebas-calculator.html');
assert(existsSync(file), 'DPPt calculator route is generated');
const html = readFileSync(file, 'utf8');
const document = parseHTML(html).document;
const pageText = document.body.textContent ?? '';
assert.equal(document.querySelector('link[rel="canonical"]')?.getAttribute('href'), 'https://pokelore.net/dppt-feebas-calculator');
assert.equal(document.querySelector('title')?.textContent, 'Pokémon Platinum Feebas Calculator | Diamond & Pearl | PokéLore');
assert.equal(document.querySelector('meta[name="description"]')?.getAttribute('content'), 'Find your exact Feebas fishing tiles in Pokémon Platinum, Diamond & Pearl. Upload a save file or use two Jubilife lottery numbers to reveal your tiles on the map.');
assert.equal(document.querySelector('h1')?.textContent, 'Pokémon Platinum, Diamond & Pearl Feebas Tile Calculator');
assert.match(pageText, /processed locally in your browser/i);
assert.match(pageText, /never uploaded, stored, or sent to Pok[eé]Lore/i);
assert.match(pageText, /This calculator requires JavaScript to run\./);
assert.match(pageText, /two consecutive Jubilife TV lottery numbers/i);
assert.match(pageText, /Use this free Feebas tile calculator to locate the fishing spots/i);
assert.match(pageText, /The calculator displays the results on an interactive map/i);
assert.match(pageText, /Beauty and the 'Bas/i);
assert.match(pageText, /Evolving Feebas to Milotic Via Beauty/i);
assert.match(pageText, /How to Find Feebas in Pokemon Platinum, Diamond, and Pearl/i);
assert.match(pageText, /Option 1: Upload Your Save File/i);
assert.match(pageText, /Option 2: Enter Two Lottery Numbers/i);
assert.match(pageText, /Understanding Map Modes/i);
assert.match(pageText, /Important Feebas Fishing Tips/i);
assert.match(pageText, /Supported Games/i);
assert.match(pageText, /Frequently Asked Questions/i);
assert(!html.includes('data:application/octet-stream') && !html.includes('ArrayBuffer('), 'No save-file payload is serialized into HTML');
const island = [...document.querySelectorAll('astro-island')].find(node => node.getAttribute('component-url')?.includes('DpptFeebasCalculatorTool'));
assert(island, 'DPPt calculator React island exists');
assert.equal(island.getAttribute('client'), 'load', 'Calculator hydrates immediately');
const props = island.getAttribute('props') ?? '';
assert(props.length < 2000, `Island props stay compact (${props.length} bytes)`);
assert(!props.includes('fishableTiles') && !props.includes('dpptFeebas'), 'Map data is not serialized into island props');
const map = join(dist, 'images', 'maps', 'mt-coronet-feebas-lake.png');
assert(existsSync(map), 'Mt. Coronet map remains a route asset');
const sitemap = readFileSync(join(dist, 'sitemap.xml'), 'utf8');
assert.equal((sitemap.match(/<loc>https:\/\/pokelore\.net\/dppt-feebas-calculator<\/loc>/g) ?? []).length, 1, 'Route appears once in sitemap');
console.log(JSON.stringify({ html: statSync(file).size, htmlGzip: gzipSync(html).length, islandProps: props.length, islandJs: statSync(join(dist, decodeURIComponent(island.getAttribute('component-url')))).size, map: statSync(map).size }, null, 2));
console.log('PASS DPPt Feebas calculator: static shell, no-JS content, local-only wording, compact immediate island, and map asset.');
